/**
 * Client-side script string that initializes language state from localStorage
 * and updates all [data-i18n] and [data-i18n-html] elements dynamically on language switch.
 */
export const i18nInitScript = `
(function() {
  const dict = ${JSON.stringify(translations)};
  
  function getLang() {
    return localStorage.getItem('balika_lang') || 'ne';
  }

  function setLang(lang) {
    localStorage.setItem('balika_lang', lang);
    document.documentElement.lang = lang;
    updatePageText(lang);
  }

  function updatePageText(lang) {
    const d = dict[lang] || dict['en'];
    
    // Update elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key && d[key]) {
        el.textContent = d[key];
      }
    });

    // Update elements with data-i18n-html attribute
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (key && d[key]) {
        el.innerHTML = d[key];
      }
    });

    // Update language toggle buttons
    document.querySelectorAll('[data-lang-toggle]').forEach(btn => {
      const textEl = btn.querySelector('.lang-text') || btn;
      textEl.textContent = lang === 'en' ? 'नेपाली' : 'English';
      btn.setAttribute('aria-label', lang === 'en' ? 'Switch to Nepali' : 'Switch to English');
    });

    // Dispatch global event for custom components
    window.dispatchEvent(new CustomEvent('languageChange', { detail: { lang } }));
  }

  // Expose toggle function globally
  window.toggleBalikaLanguage = function() {
    const current = getLang();
    const next = current === 'en' ? 'ne' : 'en';
    setLang(next);
  };

  function applyLang() {
    const lang = getLang();
    document.documentElement.lang = lang;
    updatePageText(lang);
  }

  // Run on initial DOM ready and Astro view transitions
  document.addEventListener('DOMContentLoaded', applyLang);
  document.addEventListener('astro:page-load', applyLang);
  document.addEventListener('astro:after-swap', applyLang);
})();
`;
